-- 057: sampled uptime & anonymized database diagnostics.
-- No raw SQL, auth tokens, IPs, customer identifiers, or response bodies are stored.
CREATE TABLE IF NOT EXISTS public.admin_uptime_checks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint UNIQUE,
  requested_at timestamptz NOT NULL DEFAULT now(),
  checked_at timestamptz,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','ok','error','unanswered')),
  http_status integer
);
CREATE INDEX IF NOT EXISTS idx_admin_uptime_checks_requested ON public.admin_uptime_checks (requested_at DESC);
ALTER TABLE public.admin_uptime_checks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_uptime_checks FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.admin_uptime_checks TO service_role;

CREATE OR REPLACE FUNCTION public.admin_uptime_tick()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  UPDATE public.admin_uptime_checks c
     SET status = CASE WHEN r.timed_out OR r.error_msg IS NOT NULL THEN 'error'
                       WHEN r.status_code BETWEEN 200 AND 299 THEN 'ok'
                       ELSE 'error' END,
         checked_at = now(),
         http_status = r.status_code
    FROM net._http_response r
   WHERE c.request_id = r.id AND c.status = 'pending';
  -- No response is NOT proof that the application was down.
  UPDATE public.admin_uptime_checks
     SET status = 'unanswered', checked_at = now()
   WHERE status = 'pending' AND requested_at < now() - interval '3 minutes';
  DELETE FROM public.admin_uptime_checks WHERE requested_at < now() - interval '30 days';
  INSERT INTO public.admin_uptime_checks (request_id)
  SELECT net.http_get(
    url := 'https://shopee-bot-fj0w.onrender.com/health/ready',
    timeout_milliseconds := 12000
  );
END;
$$;
REVOKE ALL ON FUNCTION public.admin_uptime_tick() FROM PUBLIC, anon, authenticated;
-- cron executor (postgres) owns the invocation; service_role only reads aggregates.
SELECT cron.schedule(
  'auto-orbital-uptime-sample-v1', '*/5 * * * *',
  'SELECT public.admin_uptime_tick();'
);

CREATE OR REPLACE FUNCTION public.admin_operations_snapshot()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
SELECT jsonb_build_object(
  'collected_at', now(),
  'database', jsonb_build_object(
    'active', (SELECT count(*) FROM pg_catalog.pg_stat_activity WHERE datname=current_database() AND state='active'),
    'idle', (SELECT count(*) FROM pg_catalog.pg_stat_activity WHERE datname=current_database() AND state='idle'),
    'idle_in_transaction', (SELECT count(*) FROM pg_catalog.pg_stat_activity WHERE datname=current_database() AND state='idle in transaction'),
    'blocked', (SELECT count(*) FROM pg_catalog.pg_stat_activity WHERE datname=current_database() AND cardinality(pg_catalog.pg_blocking_pids(pid))>0),
    'max_connections', current_setting('max_connections')::integer
  ),
  'queries', jsonb_build_object(
    'tracked_statements', (SELECT count(*) FROM extensions.pg_stat_statements WHERE dbid=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database())),
    'slow_patterns', (SELECT count(*) FROM extensions.pg_stat_statements
        WHERE dbid=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database())
          AND calls>=5 AND mean_exec_time>=50),
    'worst', (SELECT coalesce(jsonb_agg(to_jsonb(z)), '[]'::jsonb) FROM (
      SELECT row_number() OVER (ORDER BY mean_exec_time DESC)::integer AS rank,
             calls::bigint, round(mean_exec_time::numeric, 1) AS mean_ms,
             round(max_exec_time::numeric, 1) AS max_ms,
             round(total_exec_time::numeric, 1) AS total_ms
      FROM extensions.pg_stat_statements
      WHERE dbid=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database())
        AND calls >= 5
      ORDER BY mean_exec_time DESC LIMIT 5
    ) z)
  ),
  'uptime', jsonb_build_object(
    'status', CASE WHEN (SELECT count(*) FROM public.admin_uptime_checks WHERE status<>'pending')=0
               THEN 'no_samples' ELSE 'sampled' END,
    'ok', (SELECT count(*) FROM public.admin_uptime_checks WHERE status='ok'),
    'error', (SELECT count(*) FROM public.admin_uptime_checks WHERE status='error'),
    'unanswered', (SELECT count(*) FROM public.admin_uptime_checks WHERE status='unanswered'),
    'latest', (SELECT status FROM public.admin_uptime_checks WHERE status<>'pending' ORDER BY requested_at DESC LIMIT 1),
    'latest_at', (SELECT requested_at FROM public.admin_uptime_checks WHERE status<>'pending' ORDER BY requested_at DESC LIMIT 1),
    'recent', (SELECT coalesce(jsonb_agg(jsonb_build_object(
      'at', t.requested_at, 'status', t.status) ORDER BY t.requested_at), '[]'::jsonb)
      FROM (SELECT requested_at,status FROM public.admin_uptime_checks WHERE status<>'pending' ORDER BY requested_at DESC LIMIT 48) t)
  )
);
$$;
REVOKE ALL ON FUNCTION public.admin_operations_snapshot() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.admin_operations_snapshot() TO service_role;
