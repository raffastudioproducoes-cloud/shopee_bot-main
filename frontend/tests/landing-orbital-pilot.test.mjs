test("V3.2 dá profundidade real somente aos cards e mantém a transição produto → anúncio", async () => {
  const source = await read("src/pages/OrbitalPilotPage.tsx")
  const css = await read("src/pages/OrbitalPilotPage.css")
  const cards = source.slice(source.indexOf("function Sheet("), source.indexOf("const lines ="))
  assert.match(cards, /translate3d\(/)
  assert.match(cards, /rotateX\(/)
  assert.match(cards, /rotateY\(/)
  assert.match(cards, /const z = lerp\(/)
  assert.match(cards, /const turn = convert \* 180/)
  assert.match(cards, /const visibility = born \* \(1 - exit\)/)
  assert.match(cards, /--ao3-sheet-opacity/)
  assert.doesNotMatch(cards, /opacity: born \* \(1 - exit\)/)
  assert.match(cards, /DIVULGAÇÃO/)
  assert.doesNotMatch(cards, /scaleX\(/)
  assert.match(css, /\.ao3-sheet\{[^}]*transform-style:preserve-3d/)
  assert.match(css, /\.ao3-sheet::before\{[^}]*translateZ\(0\);backface-visibility:hidden;opacity:var\(--ao3-sheet-opacity,1\)/)
  assert.match(css, /backface-visibility:hidden/)
  assert.match(css, /\.ao3-sheet-back\{backface-visibility:visible;transform:rotateY\(180deg\) translateZ\(5px\)/)
  assert.match(source, /const DURATION_MS = 10_000/)
  assert.match(source, /function OrbitalSignature/)
})
